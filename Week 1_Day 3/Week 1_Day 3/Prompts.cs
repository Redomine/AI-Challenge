namespace Week_1_Day_3;

internal static class Prompts
{
    private const string ResultFormat = "Заверши ответ отдельной строкой строго в формате: TDEE_RESULT: <число>";

    public static string Direct(string personData) => $$"""
        Рассчитай примерный суточный расход калорий человека.

        Данные человека:
        {{personData}}

        {{ResultFormat}}
        """;

    public static string StepByStep(string personData) => $$"""
        Рассчитай примерный суточный расход калорий человека. Решай пошагово.
        Покажи формулу базового обмена, коэффициент активности, BMR и итоговый TDEE.

        Данные человека:
        {{personData}}

        {{ResultFormat}}
        """;

    public static string CreateSolutionPrompt(string personData) => $$"""
        Составь точный и самодостаточный промпт для нейросети, которая должна рассчитать
        примерный суточный расход калорий человека по формуле Миффлина — Сан Жеора.
        Промпт должен требовать показать формулу, подстановку значений, BMR, коэффициент
        активности и итоговый TDEE, а также завершить ответ строкой
        «TDEE_RESULT: <число>».

        Сначала выведи готовый промпт между строками PROMPT_START и PROMPT_END.
        Затем сам реши задачу по этому промпту и выведи расчёт.

        Данные человека:
        {{personData}}

        {{ResultFormat}}
        """;

    public static string UseGeneratedPrompt(string generatedPrompt) => $$"""
        {{generatedPrompt}}

        {{ResultFormat}}
        """;

    public static string ExpertGroup(string personData) => $$"""
        Рассчитайте примерный суточный расход калорий человека. Ответьте как группа экспертов:

        1. Аналитик — выполняет расчёт по формуле Миффлина — Сан Жеора, показывает BMR,
           выбранный коэффициент активности и TDEE.
        2. Врач-диетолог — проверяет исходные данные и объясняет, как интерпретировать
           полученный результат с учётом ограничений расчётной формулы.
        3. Критик — ищет ошибки в расчёте и сомнительные допущения каждого эксперта.

        После отдельных заключений сформируйте общий итог с примерным суточным расходом
        в килокалориях. Не ставьте диагнозов и явно укажите, что результат является оценкой.

        Данные человека:
        {{personData}}

        {{ResultFormat}}
        """;
}
