def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


@contextmanager
def _fake_ollama_semantic(model_name: str = "fake", dim: int = 8):
    """Фейковый Ollama, который выдаёт эмбеддинги по «мешку слов».

    Каждой позиции уникального слова в общем словаре всех запросов
    соответствует своё измерение в диапазоне ``[0, dim)``. Это даёт
    детерминированный и предсказуемый косинус: запрос «про серверы» точно
    ранжирует чанки, где есть это слово, выше остальных.
    """

    state = {"vocab": {}, "next": 0}
    lock = threading.Lock()

    def _vector(text: str) -> List[float]:
        with lock:
            mapping = state["vocab"]
            nxt = state["next"]
            words = [w for w in text.lower().split() if w]
            for w in words:
                if w not in mapping:
                    mapping[w] = nxt % dim
                    nxt += 1
            # L2-нормированный bag-of-hash → стабильный косинус.
            vec = [0.0] * dim
            for w in words:
                vec[mapping[w]] += 1.0
            norm = sum(x * x for x in vec) ** 0.5 or 1.0
            return [x / norm for x in vec]

    class H(http.server.BaseHTTPRequestHandler):
        def log_message(self, *a, **k):
            return

        def handle_one_request(self):  # type: ignore[override]
            try:
                super().handle_one_request()
            finally:
                try:
                    self.connection.shutdown(2)
                except OSError:
                    pass
                self.connection.close()

        def do_GET(self):  # noqa: N802
            if self.path == "/api/tags":
                self.send_response(200)
                self.end_headers()
                self.wfile.write(b"{}")
                return
            self.send_response(404)
            self.end_headers()

        def do_POST(self):  # noqa: N802
            length = int(self.headers.get("Content-Length", "0"))
            payload = json.loads(self.rfile.read(length) or b"{}")
            inputs = payload.get("input", [])
            vecs = [_vector(t) for t in inputs]
            body = {"model": model_name, "embeddings": vecs}
            data = json.dumps(body).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

    port = _free_port()
    httpd = http.server.HTTPServer(
        ("127.0.0.1", port), H, bind_and_activate=False,
    )
    httpd.allow_reuse_address = True
    httpd.server_bind()
    httpd.server_activate()
    th = threading.Thread(target=httpd.serve_forever, daemon=True)
    th.start()
    try:
        yield f"http://127.0.0.1:{port}", state
    finally:
        httpd.shutdown()
        httpd.server_close()


