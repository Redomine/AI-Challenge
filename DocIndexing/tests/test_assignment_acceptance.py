    # 2. Детерминизм: chunk_id и количество стабильны между прогонами
    # ------------------------------------------------------------------

    def test_chunk_ids_and_counts_stable_across_reruns(self) -> None:
        """Повторный прогон в той же директории даёт те же chunk_id и числа.

        Идемпотентность обеспечивается ``INSERT OR REPLACE`` по ``chunk_id``:
        после второго прогона число строк и набор идентификаторов совпадают
        с первым.
        """

        import sqlite3

        out_a = self.dir / "out_a"
        out_b = self.dir / "out_b"

        def _run(out_dir: Path) -> dict:
            with _fake_ollama_semantic() as (url, _):
                cfg = self._make_cfg(url=url, output_dir=out_dir)
                originals = self._patch_build()
                try:
                    return build_mod.build_index(cfg)
                finally:
                    self._unpatch_build(originals)

        def _chunk_ids(db_path: Path) -> list[str]:
            # ``sqlite3.connect`` как context manager НЕ закрывает соединение:
            # __enter__/__exit__ обрабатывают только транзакции. Поэтому
            # оборачиваем в ``contextlib.closing``, иначе на Windows файл
            # остаётся залоченным до сборщика мусора и выдаёт
            # ``ResourceWarning: unclosed database``.
            with contextlib.closing(sqlite3.connect(str(db_path))) as conn:
                return sorted(
                    r[0] for r in conn.execute(
                        "SELECT chunk_id FROM chunks"
                    ).fetchall()
                )

        metrics_a = _run(out_a)
        fixed_db_a = self._make_cfg(url="unused", output_dir=out_a).fixed_db()
        struct_db_a = self._make_cfg(url="unused", output_dir=out_a).structural_db()

        ids_a_fixed = _chunk_ids(fixed_db_a)
        ids_a_struct = _chunk_ids(struct_db_a)

        # Второй прогон в другой output_dir — независимая БД.
        metrics_b = _run(out_b)
        fixed_db_b = self._make_cfg(url="unused", output_dir=out_b).fixed_db()
        struct_db_b = self._make_cfg(url="unused", output_dir=out_b).structural_db()

        self.assertEqual(
            metrics_a["chunks"]["fixed"]["count"],
            metrics_b["chunks"]["fixed"]["count"],
        )
        self.assertEqual(
            metrics_a["chunks"]["structural"]["count"],
            metrics_b["chunks"]["structural"]["count"],
        )

        ids_b_fixed = _chunk_ids(fixed_db_b)
        ids_b_struct = _chunk_ids(struct_db_b)

        # chunk_id детерминирован от текста + стратегии → повторный прогон
        # в другой директории даёт ровно тот же набор идентификаторов.
        self.assertEqual(ids_a_fixed, ids_b_fixed)
        self.assertEqual(ids_a_struct, ids_b_struct)
        self.assertGreater(len(ids_a_fixed), 0)
        self.assertGreater(len(ids_a_struct), 0)
        # И они уникальны.
        self.assertEqual(len(ids_a_fixed), len(set(ids_a_fixed)))
        self.assertEqual(len(ids_a_struct), len(set(ids_a_struct)))

